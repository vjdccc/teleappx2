_DIRS = [os.path.join(HERE, "Voic"), os.path.join(HERE, "Arab", "helpers", "styles", "Voic"),
         os.path.join(HERE, "..", "Arab-main", "Arab", "helpers", "styles", "Voic"),
         os.path.join(HERE, "..", "Voic")]


def _find(name):
    for d in _DIRS:
        p = os.path.join(d, name)
        if os.path.exists(p):
            return p
    return None


def _make(num, fname):
    @zahid.on(admin_cmd(pattern=f"ص{num}$"))
    async def _voice(event):
        path = _find(fname)
        if not path:
            return await edit_delete(event, f"**🝳 ⦙  ملف الصوت `{fname}` غير موجود، ضعه في مجلد `Voic` بجانب السورس**", 6)
        rid = await reply_id(event)
        await event.client.send_file(event.chat_id, path, voice_note=True, reply_to=rid)
        await event.delete()
    return _voice


for _n, _f in VOICES.items():
    _make(_n, _f)
